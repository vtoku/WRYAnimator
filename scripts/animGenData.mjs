// Regenerate src/anim/unityAvatarData.ts from a Unity probe run.
//
//   node scripts/animProbeInput.mjs <reference.wanim> probe-in.json
//   node scripts/animUnity.mjs run <scratchUnityProject> probe-in.json probe-out.json
//   node scripts/animGenData.mjs probe-in.json probe-out.json
//
// The reference recording defines the avatar the muscle axes are exact for.
// Changing it changes every exported .anim slightly — re-run
// `npm run animCheck -- <take.wanim> --unity <scratchUnityProject>` afterwards.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const [inPath, outPath, tsPath] = process.argv.slice(2);
if (!inPath || !outPath) { console.error("usage: animGenData.mjs <probe-in.json> <probe-out.json> [out.ts]"); process.exit(2); }
const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const o = JSON.parse(readFileSync(outPath, "utf8")), i = JSON.parse(readFileSync(inPath, "utf8"));
const f = (a, d = 7) => "[" + Array.from(a).map((v) => +(+v).toFixed(d)).join(", ") + "]";
const rows = (a, n, d) => { const out = []; for (let b = 0; b < 55; b++) out.push("  " + f(a.slice(b * n, b * n + n), d) + ", // " + i.names[b]); return out.join("\n"); };
const ts = `// GENERATED by scripts/animGenData.mjs from a Unity ${o.unity} probe (scripts/unity/AnimProbe.cs) — do not edit by hand.
// Unity's humanoid muscle axes for a reference T-pose avatar, in UNITY space (left-handed), indexed by
// HumanBodyBones. local = preQ * ZYRoll(dof * sign) * conj(postQ). See src/anim/humanoid.ts.

/** Per bone: muscle index for dof X (roll), Y, Z; -1 = that dof has no muscle. */
export const MUSCLE_FROM_BONE: number[][] = [
${rows(o.muscleFromBone, 3, 0)}
];
export const PRE_Q: number[][] = [
${rows(o.preQ, 4)}
];
export const POST_Q: number[][] = [
${rows(o.postQ, 4)}
];
export const DOF_SIGN: number[][] = [
${rows(o.sign, 3, 0)}
];
/** The reference avatar's bind offsets (parent-relative, Unity space, meters). */
export const REF_BIND: number[][] = [
${rows(i.bind, 3, 5)}
];
export const MUSCLE_NAMES: string[] = ${JSON.stringify(o.muscleNames)};
/** Default muscle range, degrees. */
export const MUSCLE_MIN: number[] = ${f(o.muscleMin, 2)};
export const MUSCLE_MAX: number[] = ${f(o.muscleMax, 2)};
`;
const dest = tsPath ?? join(repo, "src", "anim", "unityAvatarData.ts");
writeFileSync(dest, ts);
console.log("wrote", dest);
